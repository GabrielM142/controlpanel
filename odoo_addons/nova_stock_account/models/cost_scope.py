"""Cost of sales for OMEGA margins, as booked by Odoo itself.

With continental accounting and real-time valuation, Odoo posts the cost when stock leaves:
a journal entry generated by the stock move, on the product category's stock output account
(Inventario -> Configuración -> Categorías de producto -> "Cuenta de salida de stock"). That
amount is the cost of that day (AVCO/FIFO at delivery time), not today's average.

account_move_line keeps its fixed scope (receivable, income, direct cost) and additionally
exports, per authorized company, the lines on those output accounts that come from a stock
move. Vendor bills that may share the same account are excluded (no stock_move_id).
"""
from odoo import models
from odoo.osv import expression


class NovaExportDatasetCost(models.Model):
    _inherit = "nova.export.dataset"

    def _nova_cost_account_ids(self, company_ids):
        Category = self.env["product.category"].sudo()
        accounts = set()
        for company in self.env["res.company"].sudo().browse(company_ids):
            for category in Category.with_company(company).search([]):
                account = category.property_stock_account_output_categ_id
                if account:
                    accounts.add(account.id)
        return sorted(accounts)

    def _nova_company_domain(self, spec, company_ids):
        domain = super()._nova_company_domain(spec, company_ids)
        if spec.get("key") != "account_move_line" or "stock_move_id" not in self.env["account.move"]._fields:
            return domain
        accounts = self._nova_cost_account_ids(company_ids)
        if not accounts:
            return domain
        cost = [("company_id", "in", company_ids), ("account_id", "in", accounts),
                ("move_id.stock_move_id", "!=", False)]
        return expression.OR([domain, cost])
